<h2>Pengulangan For</h2>
<h5>Pada contoh ini digunakan decrement (pengurangan), 
    sehingga nilai awal dimulai dari 10 dan akan terus berkurang sampai lebih dari 0.
</h5>
<?php
//pengulangan for

for($hitung = 10; $hitung > 0; $hitung--){
    echo "Hitungan ke : " . $hitung . "<br>"; 
}


?>

